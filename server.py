# ============================================================
# 5. صفحة استقبال البيانات (الروت المطلوب)
# ============================================================
@app.route('/data', methods=['GET', 'POST'])
def send_message():
    # 5.1 تحديد نوع الطلب
    if request.method == 'POST':
        # إذا كان الطلب POST: نقرأ البيانات من جسم الطلب
        msg = request.data.decode()
    else:
        # إذا كان الطلب GET: نقرأ البيانات من رابط الطلب
        msg = request.args.get('msg', 'GET request test')
    
    # 5.2 بناء رابط إرسال الرسالة إلى تليجرام
    url = f"https://api.telegram.org/bot{TOKEN}/sendMessage"
    
    # 5.3 إعداد البيانات لإرسالها إلى تليجرام
    data = {
        "chat_id": CHAT_ID,
        "text": msg
    }
    
    # 5.4 إرسال الرسالة إلى تليجرام
    try:
        # محاولة إرسال الرسالة
        response = requests.post(url, json=data)
        
        # التحقق من نجاح الإرسال
        if response.status_code == 200:
            return f"✅ تم الإرسال: {msg}"
        else:
            return f"❌ فشل الإرسال: {response.text}"
    except Exception as e:
        # إذا فشل الإرسال، نعيد رسالة الخطأ
        return f"❌ خطأ: {str(e)}"

